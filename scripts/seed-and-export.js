function seed() {
  mkd(publicDir, { recursive: true });
  mkd(join(root, "src", "data"), { recursive: true });

  const db = new DatabaseSync(dbPath);
  db.exec("DROP TABLE IF EXISTS pets;");
  db.exec(`
    CREATE TABLE pets (
      id INTEGER PRIMARY KEY,
      name TEXT,
      species TEXT,
      breed TEXT,
      age_years REAL,
      gender TEXT,
      status TEXT NOT NULL,
      description TEXT,
      location TEXT,
      date_reported TEXT,
      image_url TEXT,
      contact_name TEXT,
      contact_phone TEXT,
      contact_email TEXT,
      reward_amount REAL,
      is_vaccinated INTEGER,
      is_sterilized INTEGER
    );
  `);

  const stmt = db.prepare(`
    INSERT INTO pets (
      id, name, species, breed, age_years, gender, status, description,
      location, date_reported, image_url, contact_name, contact_phone,
      contact_email, reward_amount, is_vaccinated, is_sterilized
    ) VALUES (
      @id, @name, @species, @breed, @age_years, @gender, @status, @description,
      @location, @date_reported, @image_url, @contact_name, @contact_phone,
      @contact_email, @reward_amount, @is_vaccinated, @is_sterilized
    );
  `);

  db.exec("BEGIN;");
  try {
    for (const row of pets) stmt.run(row);
    db.exec("COMMIT;");
  } catch (err) {
    db.exec("ROLLBACK;");
    throw err;
  }

  const exported = db.prepare("SELECT * FROM pets ORDER BY id ASC").all();
  writeFileSync(dataOut, JSON.stringify(exported, null, 2), "utf-8");

  if (!existsSync(nojekyll)) {
    writeFileSync(nojekyll, "", "utf-8");
  }

  console.log(`Seeded ${exported.length} pets into ${dbPath}`);
  console.log(`Exported dataset to ${dataOut}`);
  db.close();
}

seed();
